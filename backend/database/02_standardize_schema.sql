-- STEP 2 of 2: standardize the database design.
-- Run this once, as a whole, after 01_backup.sql. It runs in a single transaction:
-- if anything fails, nothing is changed.
--
-- What it does
--   1. Fixed-value text columns become small numeric codes (smallint) that point to
--      lookup tables (concern_category, operational_status, accomplishment_category,
--      checklist_status, fund_source, supply_unit, log_action, record_table,
--      notification_type, file_type). The website still shows the text.
--   2. Lookup tables (province, role, department, statuses, ...) use smallint keys.
--      Everything else uses integer keys instead of bigint, and foreign keys match
--      the type of the column they point to.
--   3. The uuid primary keys of project_accomplishment and project_document_checklist
--      become integer identity columns.
--   4. Every timestamp becomes timestamptz.
--   5. files.file_size becomes a number (bytes); project.year_launched becomes smallint.
--   6. project_status and user_status get is_active / is_system / sort_order so that
--      custom statuses can be added from the website.

BEGIN;

-- ---------------------------------------------------------------- helpers
CREATE FUNCTION pg_temp.drop_checks(p_tbl regclass, p_cols text[]) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT DISTINCT c.conname
    FROM pg_constraint c
    JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = ANY (c.conkey)
    WHERE c.conrelid = p_tbl AND c.contype = 'c' AND a.attname = ANY (p_cols)
  LOOP
    EXECUTE format('ALTER TABLE %s DROP CONSTRAINT %I', p_tbl, r.conname);
  END LOOP;
END $$;

-- text column -> smallint code pointing at a lookup table
CREATE FUNCTION pg_temp.to_lookup(p_tbl text, p_old text, p_new text, p_lk text, p_notnull boolean DEFAULT false)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE missing int;
BEGIN
  -- add any value found in the data that the lookup does not have yet
  EXECUTE format($q$
    INSERT INTO %1$I (name, sort_order)
    SELECT s.v, (SELECT coalesce(max(sort_order), 0) FROM %1$I) + row_number() OVER (ORDER BY s.v)
    FROM (SELECT DISTINCT ON (lower(btrim(%3$I::text))) btrim(%3$I::text) AS v
          FROM %2$I
          WHERE %3$I IS NOT NULL AND btrim(%3$I::text) <> ''
          ORDER BY lower(btrim(%3$I::text))) s
    WHERE NOT EXISTS (SELECT 1 FROM %1$I l WHERE lower(l.name) = lower(s.v))
  $q$, p_lk, p_tbl, p_old);

  EXECUTE format('ALTER TABLE %I ADD COLUMN %I smallint', p_tbl, p_new);

  EXECUTE format($q$
    UPDATE %1$I t SET %2$I = l.%3$I
    FROM %4$I l WHERE lower(l.name) = lower(btrim(t.%5$I::text))
  $q$, p_tbl, p_new, p_lk || '_id', p_lk, p_old);

  EXECUTE format('SELECT count(*) FROM %I WHERE btrim(%I::text) <> '''' AND %I IS NULL', p_tbl, p_old, p_new) INTO missing;
  IF missing > 0 THEN
    RAISE EXCEPTION 'to_lookup: % rows of %.% could not be matched', missing, p_tbl, p_old;
  END IF;

  PERFORM pg_temp.drop_checks(p_tbl::regclass, ARRAY[p_old]);
  EXECUTE format('ALTER TABLE %I DROP COLUMN %I', p_tbl, p_old);
  IF p_notnull THEN
    EXECUTE format('ALTER TABLE %I ALTER COLUMN %I SET NOT NULL', p_tbl, p_new);
  END IF;
  EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (%I) REFERENCES %I (%I)',
                 p_tbl, 'fk_' || p_tbl || '_' || p_new, p_new, p_lk, p_lk || '_id');
END $$;

-- change a column's type (and its sequence, if it is a serial column)
CREATE FUNCTION pg_temp.set_type(p_tbl text, p_col text, p_type text, p_using text DEFAULT NULL)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE seq text; is_identity boolean;
BEGIN
  EXECUTE format('ALTER TABLE %I ALTER COLUMN %I TYPE %s %s', p_tbl, p_col, p_type,
                 CASE WHEN p_using IS NULL THEN '' ELSE 'USING ' || p_using END);
  SELECT a.attidentity <> '' INTO is_identity
    FROM pg_attribute a WHERE a.attrelid = p_tbl::regclass AND a.attname = p_col;
  seq := pg_get_serial_sequence(p_tbl, p_col);
  IF seq IS NULL AND NOT is_identity THEN   -- sequence used in the default but not "owned" by the column
    SELECT substring(pg_get_expr(d.adbin, d.adrelid) from 'nextval\(''([^'']+)''') INTO seq
      FROM pg_attrdef d JOIN pg_attribute a ON a.attrelid = d.adrelid AND a.attnum = d.adnum
     WHERE d.adrelid = p_tbl::regclass AND a.attname = p_col;
  END IF;
  IF seq IS NOT NULL AND NOT is_identity THEN
    EXECUTE format('ALTER SEQUENCE %s AS %s', seq, p_type);
  END IF;
END $$;

-- uuid primary key -> integer identity
CREATE FUNCTION pg_temp.uuid_to_int(p_tbl text, p_col text) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  EXECUTE format('ALTER TABLE %I ADD COLUMN %I integer GENERATED BY DEFAULT AS IDENTITY', p_tbl, p_col || '_new');
  EXECUTE format('ALTER TABLE %I DROP COLUMN %I', p_tbl, p_col);          -- also drops the old primary key
  EXECUTE format('ALTER TABLE %I RENAME COLUMN %I TO %I', p_tbl, p_col || '_new', p_col);
  EXECUTE format('ALTER TABLE %I ADD PRIMARY KEY (%I)', p_tbl, p_col);
END $$;

-- ------------------------------------------------ 0. remember and drop all foreign keys
-- (they are re-created at the end, so the key types can be changed freely)
CREATE TEMP TABLE _saved_fk ON COMMIT DROP AS
  SELECT conrelid::regclass::text AS tbl, conname, pg_get_constraintdef(oid) AS def
  FROM pg_constraint
  WHERE contype = 'f' AND connamespace = 'public'::regnamespace;

DO $$
DECLARE r record;
BEGIN
  FOR r IN SELECT * FROM _saved_fk LOOP
    EXECUTE format('ALTER TABLE %s DROP CONSTRAINT %I', r.tbl, r.conname);
  END LOOP;
END $$;

