  FOREACH t IN ARRAY ARRAY['concern_category','operational_status','accomplishment_category',
                           'checklist_status','fund_source','supply_unit','log_action',
                           'record_table','notification_type','file_type']
  LOOP
    EXECUTE format($f$
      CREATE TABLE %1$I (
        %1$I_id    smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name       varchar(150) NOT NULL,
        sort_order smallint NOT NULL DEFAULT 0,
        is_active  boolean  NOT NULL DEFAULT true,
        is_system  boolean  NOT NULL DEFAULT false,
        created_at timestamptz NOT NULL DEFAULT now()
      )$f$, t);
    EXECUTE format('CREATE UNIQUE INDEX %I ON %I (lower(name))', t || '_name_uq', t);
    -- only the backend (service role) reads these tables, never the public API
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END $$;

